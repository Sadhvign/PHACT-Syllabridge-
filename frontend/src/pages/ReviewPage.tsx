function initialDrafts(revision: Revision): Drafts {
  const recs: Drafts["recs"] = {};
  revision.content.recommendations?.recommendations.forEach((r) => {
    recs[r.id] = {
      title: r.title,
      target: r.target,
      proposed_change: r.proposed_change ?? "",
      recommendation: r.recommendation,
      coursework_description: r.coursework_description ?? "",
      rationale: r.rationale,
      implementation_steps: r.implementation_steps,
      assignment: {
        title: r.assignment?.title ?? "",
        student_prompt: r.assignment?.student_prompt ?? "",
        deliverable: r.assignment?.deliverable ?? "",
        ai_policy: r.assignment?.ai_policy ?? "",
      },
      excluded: !!r.excluded,
    };
  });
  const objs: Drafts["objs"] = {};
  revision.content.competencies?.objectives.forEach((o) => {
    objs[o.id] = { coverage: o.coverage, gap_notes: o.gap_notes, excluded: !!o.excluded };
  });
  return { recs, objs };
}

function diff<T extends Record<string, unknown>>(before: T, after: T): Partial<T> {
  const changes: Partial<T> = {};
  (Object.keys(after) as (keyof T)[]).forEach((k) => {
    if (JSON.stringify(before[k]) !== JSON.stringify(after[k])) changes[k] = after[k];
  });
  return changes;
}

function buildEdits(base: Drafts, current: Drafts) {
  const recommendations: Record<string, Partial<RecDraft>> = {};
  Object.entries(current.recs).forEach(([id, d]) => {
    const changes = diff(base.recs[id], d);
    if (Object.keys(changes).length) recommendations[id] = changes;
  });
  const competencies: Record<string, Partial<ObjDraft>> = {};
  Object.entries(current.objs).forEach(([id, d]) => {
    const changes = diff(base.objs[id], d);
    if (Object.keys(changes).length) competencies[id] = changes;
  });
  const edits: Record<string, Record<string, unknown>> = {};
  if (Object.keys(recommendations).length) edits.recommendations = recommendations;
  if (Object.keys(competencies).length) edits.competencies = competencies;
  return edits;
}

function InputModal({
  analysisId,
  redactions,
  open,
  onClose,
}: {
  analysisId: string;
  redactions: Record<string, number>;
  open: boolean;
  onClose: () => void;
}) {
  const [text, setText] = useState<string | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    if (!open) return;
    setText(null);
    setError("");
    api<{ text: string }>(`/api/analyses/${analysisId}/input`)
      .then((r) => setText(r.text))
      .catch((e: ApiError) => setError(e.message));
  }, [analysisId, open]);

  useEffect(() => {
    if (!open) return;
    function onKey(e: KeyboardEvent) {
      if (e.key === "Escape") onClose();
    }
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open, onClose]);

  if (!open) return null;

  return (
    <div className="modal-backdrop" role="presentation" onClick={onClose}>
      <div
        className="modal-card input-modal"
        role="dialog"
        aria-modal="true"
        aria-labelledby="input-modal-title"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="modal-head">
          <div>
            <h2 id="input-modal-title" className="panel-title">
              What the AI read
            </h2>
            <p className="privacy-line">
              <ShieldCheck aria-hidden="true" />
              {privacySummary(redactions)}
            </p>
          </div>
          <button type="button" className="icon-button" onClick={onClose} aria-label="Close">
            <X aria-hidden="true" />
          </button>
        </div>
        {error ? (
          <p className="hint">{error}</p>
        ) : text === null ? (
          <p className="hint">Loading…</p>
        ) : (
          <pre className="input-text modal-input-text">{text}</pre>
        )}
      </div>
    </div>
  );
}

