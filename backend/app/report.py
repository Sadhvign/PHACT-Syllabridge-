"""DOCX and PDF rendering of an approved result revision.

Content is shaded by who wrote it: AI-generated text that faculty kept, text faculty edited,
and the ASPPH admin's repository review.
"""

from dataclasses import dataclass, field
from io import BytesIO

from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor
from fpdf import FPDF
from fpdf.fonts import FontFace

from app import agents
from app.provenance import EDITED, KEPT

CATEGORY_LABELS = {
    "TEACHING_METHODS": "Teaching methods",
    "ASSESSMENT": "Assessment",
    "CONTENT_ENHANCEMENT": "Content enhancement",
}
COVERAGE_LABELS = {"STRONG": "Strong", "PARTIAL": "Partial", "GAP": "Gap"}
DISCLAIMER = (
    "AI-assisted draft generated by PHACT from approved ASPPH sources, then reviewed, edited, "
    "and approved by the faculty member named above. Citations refer to the source versions "
    "available when the analysis ran."
)

AI, FACULTY, ADMIN = "AI", "FACULTY", "ADMIN"
FILLS = {AI: (227, 240, 251), FACULTY: (255, 241, 194), ADMIN: (223, 243, 228)}
LEGEND = (
    (AI, "AI-generated, kept by faculty"),
    (FACULTY, "Edited by faculty"),
    (ADMIN, "ASPPH admin review"),
)


def _hex(owner: str) -> str:
    return "%02X%02X%02X" % FILLS[owner]


@dataclass
class ReportData:
    course_title: str
    course_code: str
    revision: int
    reviewer_name: str
    approved_at: str
    content: dict
    provenance: dict = field(default_factory=dict)
    university_name: str = ""
    # Present only on the copy stored in the ASPPH repository.
    admin_review: dict | None = None

    @property
    def heading(self) -> str:
        if not self.course_code or self.course_title.startswith(self.course_code):
            return self.course_title
        return f"{self.course_code}: {self.course_title}"

    def _all(self, part: str, key: str) -> list[dict]:
        return (self.content.get(part) or {}).get(key, [])

    def recommendations(self) -> list[dict]:
        return [r for r in self._all(agents.RECOMMENDATIONS, "recommendations") if not r.get("excluded")]

    def objectives(self) -> list[dict]:
        return [o for o in self._all(agents.COMPETENCIES, "objectives") if not o.get("excluded")]

    def excluded(self) -> list[str]:
        return [r["title"] for r in self._all(agents.RECOMMENDATIONS, "recommendations") if r.get("excluded")] + [
            o["objective"] for o in self._all(agents.COMPETENCIES, "objectives") if o.get("excluded")
        ]

    def section(self, part: str, key: str) -> list[dict]:
        return self._all(part, key)

    def changes(self, kind: str, item_id: str) -> tuple[str, list[str]]:
        entry = (self.provenance.get(kind) or {}).get(item_id) or {}
        return entry.get("status", KEPT), entry.get("fields", [])

    def owner(self, kind: str, item_id: str, field_name: str) -> str:
        return FACULTY if field_name in self.changes(kind, item_id)[1] else AI

    def tag(self, kind: str, item_id: str) -> tuple[str, str]:
        status, fields = self.changes(kind, item_id)
        if status == EDITED:
            return FACULTY, "Edited by faculty: " + ", ".join(f.replace("_", " ") for f in fields)
        return AI, "AI-generated, kept as written"

    def summary_rows(self) -> list[tuple[str, str]]:
        stats = self.provenance.get("stats") or {}
        rows = []
        for label, key in (("Recommendations", "recommendations"), ("Objective mappings", "objectives")):
            c = stats.get(key)
            if c:
                rows.append((label, f"{c['kept']} kept as generated, {c['edited']} edited, {c['excluded']} excluded (of {c['total']})"))
        if "ai_text_retained_percent" in stats:
            rows.append(("AI text retained", f"{stats['ai_text_retained_percent']}% of approved wording is unchanged AI text"))
        return rows

    def evidence(self) -> dict[str, dict]:
        refs: dict[str, dict] = {}
        for part in agents.PARTS:
            for item in (self.content.get(part) or {}).get("evidence", []):
                refs[item["ref"]] = item
        return refs

    def cited_sources(self) -> list[dict]:
        evidence = self.evidence()
        cited: dict[tuple, dict] = {}
        items = (
            self.recommendations()
            + self.objectives()
            + self.section(agents.COMPETENCIES, "workforce_expectations")
            + self.section(agents.COMPETENCIES, "uncovered_competencies")
        )
        for item in items:
            for ref in item.get("citations", []):
                e = evidence.get(ref)
                if e:
                    cited[(e["source_id"], e["version"])] = e
        return sorted(cited.values(), key=lambda e: e["title"])

    def citation_text(self, refs: list[str]) -> str:
        evidence = self.evidence()
        labels = [
            f"{evidence[r]['title']} (v{evidence[r]['version']})" for r in refs if r in evidence
        ]
        return "; ".join(dict.fromkeys(labels)) or "No supporting ASPPH source found"


def _approval_line(data: ReportData) -> str:
    school = f", {data.university_name}" if data.university_name else ""
    return (
        f"Approved by {data.reviewer_name}{school} on {data.approved_at[:10]} "
        f"(result version {data.revision})"
    )


def _admin_lines(review: dict) -> list[str]:
    lines = [
        f"Accepted into the ASPPH curriculum repository by {review.get('reviewer', '')} "
        f"on {review.get('decided_at', '')[:10]}.",
        f"Submitted by {review.get('submitted_by', '')} ({review.get('university', '')}) "
        f"on {review.get('submitted_at', '')[:10]}.",
    ]
    if review.get("note"):
        lines.append(f"Admin note: {review['note']}")
    return lines


# ---------------------------------------------------------------- DOCX

_SHD_SUCCESSORS = (
    "w:tabs", "w:suppressAutoHyphens", "w:kinsoku", "w:wordWrap", "w:overflowPunct",
    "w:topLinePunct", "w:autoSpaceDE", "w:autoSpaceDN", "w:bidi", "w:adjustRightInd",
    "w:snapToGrid", "w:spacing", "w:ind", "w:contextualSpacing", "w:mirrorIndents",
    "w:suppressOverlap", "w:jc", "w:textDirection", "w:textAlignment", "w:textboxTightWrap",
    "w:outlineLvl", "w:divId", "w:cnfStyle", "w:rPr", "w:sectPr", "w:pPrChange",
)


def _shd(owner: str):
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), _hex(owner))
    return shd


def _shade(paragraph, owner: str):
    paragraph._p.get_or_add_pPr().insert_element_before(_shd(owner), *_SHD_SUCCESSORS)
    return paragraph


def _shade_cell(cell, owner: str) -> None:
    cell._tc.get_or_add_tcPr().append(_shd(owner))


def _small(paragraph, text: str, color=(0x5F, 0x72, 0x7A), bold=False):
    run = paragraph.add_run(text)
    run.font.size = Pt(9)
    run.bold = bold
    run.font.color.rgb = RGBColor(*color)
    return run


def build_docx(data: ReportData) -> bytes:
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(10.5)
    doc.add_heading(data.heading, level=0)
    approval = doc.add_paragraph(_approval_line(data))
    approval.runs[0].italic = True

    legend = doc.add_table(rows=1, cols=len(LEGEND))
    for cell, (owner, label) in zip(legend.rows[0].cells, LEGEND):
        cell.text = label
        cell.paragraphs[0].runs[0].font.size = Pt(9)
        _shade_cell(cell, owner)

    if data.admin_review:
        doc.add_heading("ASPPH repository review", level=1)
        for line in _admin_lines(data.admin_review):
            _shade(doc.add_paragraph(line), ADMIN)

    rows = data.summary_rows()
    if rows:
        doc.add_heading("Review summary", level=1)
        table = doc.add_table(rows=0, cols=2)
        table.style = "Light Grid Accent 1"
        for label, value in rows:
            cells = table.add_row().cells
            cells[0].text, cells[1].text = label, value
        excluded = data.excluded()
        if excluded:
            p = doc.add_paragraph()
            _small(p, "Excluded by faculty: ", bold=True)
            _small(p, "; ".join(excluded))

    summary = (data.content.get(agents.RECOMMENDATIONS) or {}).get("course_summary")
    if summary:
        _shade(doc.add_paragraph(summary), AI)

    doc.add_heading("Proposed syllabus updates", level=1)
    intro = doc.add_paragraph()
    intro.add_run(
        "Short week and assessment lines only — matching the syllabus style. "
        "Reasons appear in the section after this list."
    ).italic = True
    for rec in data.recommendations():
        rid = rec["id"]
        owner = lambda f: data.owner("recommendations", rid, f)  # noqa: E731
        change = (rec.get("proposed_change") or "").strip() or rec.get("title", "")
        line = _shade(doc.add_paragraph(style="List Bullet"), owner("proposed_change"))
        line.add_run(f"{rec.get('target', '')}: ").bold = True
        line.add_run(change)
        assignment = rec.get("assignment") or {}
        if assignment.get("title"):
            detail = assignment["title"]
            if assignment.get("deliverable"):
                detail += f" ({assignment['deliverable']})"
            _shade(doc.add_paragraph(detail, style="List Bullet"), owner("assignment"))

    doc.add_heading("Why these updates", level=1)
    for rec in data.recommendations():
        rid = rec["id"]
        owner = lambda f: data.owner("recommendations", rid, f)  # noqa: E731
        tag_owner, tag = data.tag("recommendations", rid)
        _shade(doc.add_heading(rec["title"], level=2), owner("title"))
        _small(_shade(doc.add_paragraph(), tag_owner), tag, bold=True)
        meta = _shade(doc.add_paragraph(), owner("target"))
        meta.add_run(
            f"{CATEGORY_LABELS.get(rec['category'], rec['category'])} · Applies to: {rec['target']}"
        ).italic = True
        if rec.get("recommendation"):
            _shade(doc.add_paragraph(rec["recommendation"]), owner("recommendation"))
        if rec.get("rationale"):
            why = _shade(doc.add_paragraph(), owner("rationale"))
            why.add_run("Why it matters: ").bold = True
            why.add_run(rec["rationale"])
        for step in rec.get("implementation_steps", []):
            _shade(doc.add_paragraph(step, style="List Bullet"), owner("implementation_steps"))
        assignment = rec.get("assignment") or {}
        if any(assignment.get(k) for k in ("title", "student_prompt", "deliverable", "ai_policy")):
            heading = _shade(doc.add_paragraph(), owner("assignment"))
            heading.add_run("Assessment structure").bold = True
            if assignment.get("title"):
                _shade(doc.add_paragraph(assignment["title"]), owner("assignment"))
            if assignment.get("student_prompt"):
                _shade(doc.add_paragraph(assignment["student_prompt"]), owner("assignment"))
            if assignment.get("deliverable"):
                _shade(
                    doc.add_paragraph(f"Weight / deliverable: {assignment['deliverable']}"),
                    owner("assignment"),
                )
            if assignment.get("ai_policy"):
                _shade(
                    doc.add_paragraph(f"AI use: {assignment['ai_policy']}"),
                    owner("assignment"),
                )
        _small(doc.add_paragraph(), f"Sources: {data.citation_text(rec.get('citations', []))}")

    doc.add_heading("Competency mapping", level=1)
    table = doc.add_table(rows=1, cols=4)
    table.style = "Light Grid Accent 1"
    for cell, label in zip(table.rows[0].cells, ["Course objective", "Matched competency", "Coverage", "Gap / notes"]):
        cell.text = label
    for obj in data.objectives():
        oid = obj["id"]
        row = table.add_row().cells
        row[0].text = obj["objective"]
        row[1].text = "\n".join(obj.get("matches", [])) or "None"
        row[2].text = COVERAGE_LABELS.get(obj.get("coverage", ""), obj.get("coverage", ""))
        row[3].text = f"{obj.get('gap_notes', '')}\nSources: {data.citation_text(obj.get('citations', []))}"
        _shade_cell(row[1], AI)
        _shade_cell(row[2], data.owner("objectives", oid, "coverage"))
        _shade_cell(row[3], data.owner("objectives", oid, "gap_notes"))

    expectations = data.section(agents.COMPETENCIES, "workforce_expectations")
    if expectations:
        doc.add_heading("Workforce expectations", level=2)
        for item in expectations:
            p = _shade(doc.add_paragraph(style="List Bullet"), AI)
            p.add_run(f"{item['expectation']}: ").bold = True
            p.add_run(item.get("course_alignment", ""))

    uncovered = data.section(agents.COMPETENCIES, "uncovered_competencies")
    if uncovered:
        doc.add_heading("Competencies to consider adding", level=2)
        for item in uncovered:
            p = _shade(doc.add_paragraph(style="List Bullet"), AI)
            p.add_run(f"{item['competency']}: ").bold = True
            p.add_run(item.get("suggestion", ""))

    doc.add_heading("Sources", level=1)
    for e in data.cited_sources():
        doc.add_paragraph(f"{e['title']} — version {e['version']} ({e['source_type']})", style="List Bullet")
    note = doc.add_paragraph()
    note.add_run(DISCLAIMER).italic = True

    buffer = BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


# ---------------------------------------------------------------- PDF

PDF_REPLACEMENTS = str.maketrans(
    {"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u2013": "-", "\u2014": "-",
     "\u2022": "-", "\u2026": "...", "\u00a0": " ", "\u2192": "->", "\u2264": "<=", "\u2265": ">="}
)


def _latin(text: str) -> str:
    # The built-in PDF fonts only cover Latin-1.
    return str(text).translate(PDF_REPLACEMENTS).encode("latin-1", "replace").decode("latin-1")


class _Pdf(FPDF):
    def footer(self) -> None:
        self.set_y(-12)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(110)
        self.cell(0, 8, f"PHACT approved report - page {self.page_no()}", align="C")


def build_pdf(data: ReportData) -> bytes:
    pdf = _Pdf(format="Letter")
    pdf.set_auto_page_break(auto=True, margin=16)
    pdf.add_page()
    width = pdf.epw

    def text(
        value: str, size: float = 10, style: str = "", gap: float = 1.5, color: int = 20,
        fill: str | None = None,
    ) -> None:
        pdf.set_font("Helvetica", style, size)
        pdf.set_text_color(color)
        if fill:
            pdf.set_fill_color(*FILLS[fill])
        pdf.multi_cell(
            width, size * 0.5, _latin(value), new_x="LMARGIN", new_y="NEXT",
            fill=bool(fill), padding=(0.6, 1.5) if fill else 0,
        )
        pdf.ln(gap)

    text(data.heading, 18, "B", 2, 11)
    text(_approval_line(data), 9, "I", 3, 90)

    pdf.set_font("Helvetica", size=8)
    pdf.set_text_color(40)
    for owner, label in LEGEND:
        pdf.set_fill_color(*FILLS[owner])
        pdf.cell(4, 4, "", fill=True, border=0)
        pdf.cell(pdf.get_string_width(label) + 7, 4, f" {label}")
    pdf.ln(8)

    if data.admin_review:
        text("ASPPH repository review", 14, "B", 2, 11)
        for line in _admin_lines(data.admin_review):
            text(line, 9.5, gap=0, fill=ADMIN)
        pdf.ln(4)

    rows = data.summary_rows()
    if rows:
        text("Review summary", 14, "B", 2, 11)
        pdf.set_font("Helvetica", size=9)
        pdf.set_text_color(20)
        with pdf.table(col_widths=(28, 72), line_height=4.6, first_row_as_headings=False) as table:
            for label, value in rows:
                table.row([_latin(label), _latin(value)])
        excluded = data.excluded()
        if excluded:
            pdf.ln(1)
            text("Excluded by faculty: " + "; ".join(excluded), 8.5, "I", color=90)
        pdf.ln(3)

    summary = (data.content.get(agents.RECOMMENDATIONS) or {}).get("course_summary")
    if summary:
        text(summary, gap=4, fill=AI)

    text("Proposed syllabus updates", 14, "B", 2, 11)
    text(
        "Short week and assessment lines only. Reasons follow in the next section.",
        9, "I", 3, 90,
    )
    for rec in data.recommendations():
        rid = rec["id"]

        def owner_change(f: str, rid: str = rid) -> str:
            return data.owner("recommendations", rid, f)

        change = (rec.get("proposed_change") or "").strip() or rec.get("title", "")
        text(f"-  {rec.get('target', '')}: {change}", 9.5, gap=0, fill=owner_change("proposed_change"))
        assignment = rec.get("assignment") or {}
        if assignment.get("title"):
            detail = assignment["title"]
            if assignment.get("deliverable"):
                detail += f" ({assignment['deliverable']})"
            text(f"    {detail}", 9, gap=0, fill=owner_change("assignment"))
    pdf.ln(3)

    text("Why these updates", 14, "B", 2, 11)
    for rec in data.recommendations():
        rid = rec["id"]

        def owner(f: str, rid: str = rid) -> str:
            return data.owner("recommendations", rid, f)

        tag_owner, tag = data.tag("recommendations", rid)
        text(rec["title"], 11.5, "B", 0, fill=owner("title"))
        text(tag, 8, "B", 0, 70, fill=tag_owner)
        text(
            f"{CATEGORY_LABELS.get(rec['category'], rec['category'])} - Applies to: {rec['target']}",
            9, "I", 0, 90, fill=owner("target"),
        )
        if rec.get("recommendation"):
            text(rec["recommendation"], gap=0, fill=owner("recommendation"))
        if rec.get("rationale"):
            text(f"Why it matters: {rec['rationale']}", gap=0, fill=owner("rationale"))
        for step in rec.get("implementation_steps", []):
            text(f"-  {step}", 9.5, gap=0, fill=owner("implementation_steps"))
        assignment = rec.get("assignment") or {}
        if any(assignment.get(k) for k in ("title", "student_prompt", "deliverable", "ai_policy")):
            text("Assessment structure", 10, "B", 0, fill=owner("assignment"))
            if assignment.get("title"):
                text(assignment["title"], 9.5, "B", 0, fill=owner("assignment"))
            if assignment.get("student_prompt"):
                text(assignment["student_prompt"], gap=0, fill=owner("assignment"))
            if assignment.get("deliverable"):
                text(
                    f"Weight / deliverable: {assignment['deliverable']}",
                    9.5, gap=0, fill=owner("assignment"),
                )
            if assignment.get("ai_policy"):
                text(f"AI use: {assignment['ai_policy']}", 9.5, gap=0, fill=owner("assignment"))
        pdf.ln(1)
        text(f"Sources: {data.citation_text(rec.get('citations', []))}", 8.5, gap=4, color=100)

    text("Competency mapping", 14, "B", 2, 11)
    pdf.set_font("Helvetica", size=8.5)
    pdf.set_text_color(20)
    styles = {o: FontFace(fill_color=FILLS[o]) for o in FILLS}
    with pdf.table(col_widths=(32, 30, 12, 36), line_height=4.2, first_row_as_headings=True) as table:
        table.row([_latin(h) for h in ("Course objective", "Matched competency", "Coverage", "Gap / notes")])
        for obj in data.objectives():
            oid = obj["id"]
            row = table.row()
            row.cell(_latin(obj["objective"]))
            row.cell(_latin("\n".join(obj.get("matches", [])) or "None"), style=styles[AI])
            row.cell(
                _latin(COVERAGE_LABELS.get(obj.get("coverage", ""), obj.get("coverage", ""))),
                style=styles[data.owner("objectives", oid, "coverage")],
            )
            row.cell(
                _latin(f"{obj.get('gap_notes', '')}\nSources: {data.citation_text(obj.get('citations', []))}"),
                style=styles[data.owner("objectives", oid, "gap_notes")],
            )
    pdf.ln(4)

    expectations = data.section(agents.COMPETENCIES, "workforce_expectations")
    if expectations:
        text("Workforce expectations", 12, "B", 1.5, 11)
        for item in expectations:
            text(f"-  {item['expectation']}: {item.get('course_alignment', '')}", 9.5, gap=0, fill=AI)
        pdf.ln(3)

    uncovered = data.section(agents.COMPETENCIES, "uncovered_competencies")
    if uncovered:
        text("Competencies to consider adding", 12, "B", 1.5, 11)
        for item in uncovered:
            text(f"-  {item['competency']}: {item.get('suggestion', '')}", 9.5, gap=0, fill=AI)
        pdf.ln(3)

    text("Sources", 14, "B", 2, 11)
    for e in data.cited_sources():
        text(f"-  {e['title']} - version {e['version']} ({e['source_type']})", 9.5, gap=0.5)
    pdf.ln(3)
    text(DISCLAIMER, 8.5, "I", color=100)
    return bytes(pdf.output())
